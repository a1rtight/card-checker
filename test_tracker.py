import tracker
from tracker import CARD, foil, title_ok

assert title_ok("1997 POKEMON JAPANESE FOSSIL #151 MEW-HOLO PSA 9")
assert title_ok("1997 Pokemon Japanese Fossil Holo #151 Mew - PSA MINT 9")
assert not title_ok("1997 Pokemon Japanese Fossil Holo Mew #151 PSA 10 GEM MINT")
assert not title_ok("Japanese Fossil Mew PSA 9.5")
assert not title_ok("1997 Pokemon Japanese Fossil Holo Mew #151 PSA 8 NM-MT")
assert not title_ok("1999 Pokemon Fossil Mew Holo PSA 9")  # English, not Japanese
assert not title_ok("CGC 9 MINT Mew Fossil Japanese")
assert title_ok("Pokémon Mew 151 Mystery of the Fossils Holo Rare PSA 9 1997 Japanese TCG")
assert not title_ok("ANCIENT MEW PSA 9 POKEMON PROMO MEWTWO STRIKES BACK MOVIE JAPANESE")
assert not title_ok("PSA 9 Pokemon Card Mew ex SAR 347/190 Alt Art SV4a Shiny Treasure Japanese Holo")
for name, want in [("Mew #151 Holo — Japanese Fossil (1997)", "rare holo cosmos"),  # vintage holo -> galaxy
                   ("Charizard VMAX 074/073 (2020)", "rare holo vmax"),
                   ("Pikachu V 043/185 (2020)", "rare holo v"),
                   ("Umbreon Reverse Holo (2021)", "common reverse holo"),
                   ("Celebi Holo (2021)", "rare holo"),
                   ("Mewtwo Cosmos Holo Promo (2019)", "rare holo cosmos"),
                   ("Rattata (1999)", "common")]:
    CARD["name"] = name
    assert foil() == want, (name, foil())
print("ok")

# foil mask (generated by a tracker run): Mew's body no foil, galaxy background foil, outside art box no foil
import os
from PIL import Image
m = os.path.join(tracker.MASKS, "pokemon-japanese-mystery-of-the-fossils-mew-151.png")
if os.path.exists(m):
    a = Image.open(m).getchannel("A")
    at = lambda fx, fy: a.getpixel((int(a.width * fx), int(a.height * fy)))
    assert at(.53, .375) == 0, "Mew's body should not be foiled"
    assert at(.15, .16) == 255 and at(.8, .5) == 255, "art background should be foiled"
    assert at(.5, .7) == 0, "text box should not be foiled"
    print("mask ok")
